-- Executar uma vez na base avalia. Preserva os códigos e instrumentos existentes.
BEGIN;

CREATE TABLE avaliacao.status (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(12) NOT NULL UNIQUE,
    descricao varchar(100) NOT NULL
);

INSERT INTO avaliacao.status (codigo, descricao)
SELECT codigo, CASE codigo
    WHEN 'RASCUNHO' THEN 'Rascunho'
    WHEN 'EM_APLICACAO' THEN 'Em aplicação'
    WHEN 'ENCERRADO' THEN 'Encerrado'
    ELSE initcap(replace(codigo, '_', ' ')) END
FROM (
    SELECT DISTINCT status AS codigo FROM avaliacao.instrumento_avaliativo
    UNION SELECT 'RASCUNHO'
    UNION SELECT 'EM_APLICACAO'
    UNION SELECT 'ENCERRADO'
) codigos
ORDER BY codigo;

ALTER TABLE avaliacao.instrumento_avaliativo
    ADD CONSTRAINT fk_instrumento_avaliativo_status
    FOREIGN KEY (status) REFERENCES avaliacao.status (codigo)
    ON UPDATE RESTRICT ON DELETE RESTRICT;

CREATE INDEX idx_instrumento_avaliativo_status ON avaliacao.instrumento_avaliativo (status);

COMMIT;
